/**
 * services/reportService.js
 *
 * Implements UML Class: FeedbackReport
 * Attributes:
 *   - reportId: number | string (e.g. REP-0001)
 *   - generatedDate: Date string (ISO)
 *   - totalFeedback: number
 *   - resolvedFeedback: number
 * Methods:
 *   - generateReport()
 *   - viewReport()
 */
import { getAllFeedback } from './feedbackService';
import { getCurrentUser } from './authService';

const REPORTS_STORE_KEY = 'mutiara_feedback_reports_store';
const delay = (ms = 350) => new Promise((resolve) => setTimeout(resolve, ms));

function getStoredReports() {
  try {
    const raw = localStorage.getItem(REPORTS_STORE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Failed to parse reports store:', err);
  }
  return [];
}

function saveStoredReports(list) {
  try {
    localStorage.setItem(REPORTS_STORE_KEY, JSON.stringify(list));
  } catch (err) {
    console.error('Failed to save reports store:', err);
  }
}

/**
 * Generate a new comprehensive feedback progress report.
 * Matches UML: FeedbackReport.generateReport()
 *
 * @param {{ title?: string, notes?: string }} [options={}]
 * @returns {Promise<{ data: object }>}
 */
export async function generateReport(options = {}) {
  await delay(400);

  const { data: feedbackList } = await getAllFeedback();
  const reports = getStoredReports();
  const nextNum = reports.length + 1;
  const reportId = `REP-${String(nextNum).padStart(4, '0')}`;

  const totalFeedback = feedbackList.length;
  const resolvedFeedback = feedbackList.filter((f) => f.status === 'resolved').length;
  const inProgressFeedback = feedbackList.filter((f) => f.status === 'in_progress').length;
  const pendingFeedback = feedbackList.filter((f) => f.status === 'pending').length;

  const businessFeedbackCount = feedbackList.filter((f) => f.feedbackType === 'business').length;
  const residentComplaintCount = feedbackList.filter((f) => f.feedbackType !== 'business').length;

  // Breakdown by category
  const categoryCounts = {};
  feedbackList.forEach((f) => {
    const cat = f.category || 'Other';
    categoryCounts[cat] = (categoryCounts[cat] || 0) + 1;
  });

  const currentUser = getCurrentUser();
  const now = new Date().toISOString();

  const resolutionRate = totalFeedback > 0 ? Math.round((resolvedFeedback / totalFeedback) * 100) : 0;

  const newReport = {
    id: nextNum,
    reportId, // UML attribute alignment
    title: options.title || `LRT Mutiara Line Community Feedback Milestone Audit #${nextNum}`,
    generatedDate: now, // UML attribute alignment
    generated_at: now,
    generatedBy: currentUser?.name || 'Administrator',
    totalFeedback, // UML attribute alignment
    resolvedFeedback, // UML attribute alignment
    pendingFeedback,
    inProgressFeedback,
    businessFeedbackCount,
    residentComplaintCount,
    resolutionRate,
    categoryCounts,
    notes: options.notes || 'Official periodic grievance and mitigation resolution summary report.',
  };

  reports.unshift(newReport);
  saveStoredReports(reports);

  return { data: newReport };
}

/**
 * View all previously generated feedback reports.
 * Matches UML: FeedbackReport.viewReport()
 *
 * @returns {Promise<{ data: Array }>}
 */
export async function getReports() {
  await delay(200);
  const reports = getStoredReports();
  // If empty, auto-generate initial report
  if (reports.length === 0) {
    const initial = await generateReport({
      title: 'Penang LRT Alignment Initial Public Grievance Audit',
      notes: 'Initial executive baseline report summarizing early construction phase feedback.',
    });
    return { data: [initial.data] };
  }
  return { data: reports };
}

/**
 * View a single feedback report by ID.
 * Matches UML: FeedbackReport.viewReport()
 *
 * @param {string|number} reportId
 * @returns {Promise<{ data: object }>}
 */
export async function viewReport(reportId) {
  await delay(200);
  const reports = getStoredReports();
  const found = reports.find(
    (r) => r.id === Number(reportId) || r.reportId === String(reportId)
  );

  if (!found) {
    throw { response: { data: { message: 'Feedback report not found.' }, status: 404 } };
  }

  return { data: found };
}

/**
 * Export a report to downloadable CSV.
 *
 * @param {object} report
 */
export function exportReportCSV(report) {
  const rows = [
    ['Penang LRT Mutiara Line - Community Feedback & Grievance Report'],
    ['Report ID', report.reportId],
    ['Generated Date', report.generatedDate],
    ['Generated By', report.generatedBy],
    [''],
    ['Metric', 'Count', 'Percentage'],
    ['Total Feedback Received', report.totalFeedback, '100%'],
    ['Resolved Issues', report.resolvedFeedback, `${report.resolutionRate}%`],
    ['In Progress Investigations', report.inProgressFeedback, `${Math.round((report.inProgressFeedback / (report.totalFeedback || 1)) * 100)}%`],
    ['Pending Review', report.pendingFeedback, `${Math.round((report.pendingFeedback / (report.totalFeedback || 1)) * 100)}%`],
    [''],
    ['Disruption Breakdown by Type'],
    ['Commercial / Business Disruptions', report.businessFeedbackCount],
    ['Resident / Commuter Complaints', report.residentComplaintCount],
    [''],
    ['Category Breakdown'],
    ...Object.entries(report.categoryCounts || {}).map(([cat, count]) => [cat, count]),
  ];

  const csvContent = 'data:text/csv;charset=utf-8,' + rows.map((e) => e.join(',')).join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', `Mutiara_LRT_Feedback_Report_${report.reportId}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
